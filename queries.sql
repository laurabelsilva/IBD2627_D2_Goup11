-- Q14. Enrollments that do not yet have a payment.

SELECT e.enrollment_id,
       pe.name AS participant_name,
       pur.total_amount,
       e.registration_date
FROM enrollment e
JOIN purchase pur
    ON pur.purchase_id = e.purchase_id
JOIN person pe
    ON pe.person_id = pur.participant_id
LEFT JOIN payment pay
    ON pay.purchase_id = pur.purchase_id
WHERE pay.payment_id IS NULL
ORDER BY e.registration_date;


-- Q15. Validation report: cycles not containing exactly six sessions.
-- With the supplied data, this query should return zero rows.

SELECT c.cycle_id,
       COUNT(s.session_id) AS total_sessions
FROM cycle c
LEFT JOIN session s
    ON s.cycle_id = c.cycle_id
GROUP BY c.cycle_id
HAVING COUNT(s.session_id) <> 6;


-- Q16. Five sessions with the highest number of registered participants.

SELECT *
FROM v_participants_per_session
ORDER BY total_participants DESC, session_id
LIMIT 5;


