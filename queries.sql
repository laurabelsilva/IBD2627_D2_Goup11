-- View 1:
-- Every paid session credited to each participant and training program.
-- A paid package gives access to all sessions of its cycle.

CREATE OR REPLACE VIEW v_paid_training_sessions AS
SELECT pur.participant_id,
       c.training_program_id,
       s.session_id,
       s.session_date,
       2 AS credited_hours
FROM purchase pur
JOIN payment pay
    ON pay.purchase_id = pur.purchase_id
JOIN enrollment e
    ON e.purchase_id = pur.purchase_id
JOIN session s
    ON s.session_id = e.session_id
JOIN cycle c
    ON c.cycle_id = s.cycle_id
WHERE e.session_id IS NOT NULL

UNION

SELECT pur.participant_id,
       c.training_program_id,
       s.session_id,
       s.session_date,
       2 AS credited_hours
FROM purchase pur
JOIN payment pay
    ON pay.purchase_id = pur.purchase_id
JOIN enrollment e
    ON e.purchase_id = pur.purchase_id
JOIN session s
    ON s.cycle_id = e.cycle_id
JOIN cycle c
    ON c.cycle_id = s.cycle_id
WHERE e.cycle_id IS NOT NULL;


-- View 2:
-- Revenue generated by each training cycle.
-- Includes both package purchases and single-session purchases.

CREATE OR REPLACE VIEW v_revenue_per_cycle AS
SELECT c.cycle_id,
       c.start_date,
       c.end_date,
       COALESCE(SUM(revenue.total_amount), 0) AS total_revenue
FROM cycle c
LEFT JOIN (
    -- Package purchases enrolled directly in a cycle
    SELECT e.cycle_id,
           pur.total_amount
    FROM enrollment e
    JOIN purchase pur
        ON pur.purchase_id = e.purchase_id
    WHERE e.cycle_id IS NOT NULL

    UNION ALL

    -- Individual-session purchases belong to the cycle of their session
    SELECT s.cycle_id,
           pur.total_amount
    FROM enrollment e
    JOIN purchase pur
        ON pur.purchase_id = e.purchase_id
    JOIN session s
        ON s.session_id = e.session_id
    WHERE e.session_id IS NOT NULL
) AS revenue
    ON revenue.cycle_id = c.cycle_id
GROUP BY c.cycle_id, c.start_date, c.end_date;


-- View 3:
-- Invoices that still need to be sent.

CREATE OR REPLACE VIEW v_unsent_invoices AS
SELECT i.invoice_id,
       i.invoice_number,
       i.issue_date,
       pe.name AS participant_name,
       pay.amount_paid
FROM invoice i
JOIN payment pay
    ON pay.payment_id = i.payment_id
JOIN purchase pur
    ON pur.purchase_id = pay.purchase_id
JOIN participant part
    ON part.participant_id = pur.participant_id
JOIN person pe
    ON pe.person_id = part.participant_id
WHERE i.status = 'NOT_SENT';


-- View 4:
-- Number of participants registered for each session.
-- Includes individual-session and package enrollments.

CREATE OR REPLACE VIEW v_participants_per_session AS
SELECT s.session_id,
       s.topic,
       s.cycle_id,
       COUNT(DISTINCT r.participant_id) AS total_participants
FROM session s
LEFT JOIN (
    SELECT pur.participant_id,
           e.session_id
    FROM purchase pur
    JOIN enrollment e
        ON e.purchase_id = pur.purchase_id
    WHERE e.session_id IS NOT NULL

    UNION

    SELECT pur.participant_id,
           s2.session_id
    FROM purchase pur
    JOIN enrollment e
        ON e.purchase_id = pur.purchase_id
    JOIN session s2
        ON s2.cycle_id = e.cycle_id
    WHERE e.cycle_id IS NOT NULL
) AS r
    ON r.session_id = s.session_id
GROUP BY s.session_id, s.topic, s.cycle_id;


-- View 5:
-- Number of patients assigned to every homeopath.

CREATE OR REPLACE VIEW v_patient_load AS
SELECT h.homeopath_id,
       pe.name AS homeopath_name,
       COUNT(ph.patient_id) AS total_patients
FROM homeopath h
JOIN person pe
    ON pe.person_id = h.homeopath_id
LEFT JOIN patient_homeopath ph
    ON ph.homeopath_id = h.homeopath_id
GROUP BY h.homeopath_id, pe.name;


