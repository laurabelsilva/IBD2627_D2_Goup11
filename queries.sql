-- Q7. Number of patients assigned to each homeopath.

SELECT *
FROM v_patient_load
ORDER BY total_patients DESC, homeopath_name;


-- Q8. Initial and follow-up consultation count for every patient.

SELECT pat.patient_id,
       pe.name AS patient_name,
       COALESCE(c.type, 'No consultations') AS consultation_type,
       COUNT(c.consultation_id) AS total_consultations
FROM patient pat
JOIN person pe
    ON pe.person_id = pat.patient_id
LEFT JOIN consultation c
    ON c.patient_id = pat.patient_id
GROUP BY pat.patient_id, pe.name, c.type
ORDER BY pat.patient_id, consultation_type;


-- Q9. Participants registered for each session of cycle 10.
-- Includes individual enrollments and package enrollments,
-- and shows which lecturer conducts each session.

SELECT s.session_id,
       s.topic,
       lec.name AS session_lecturer,
       pe.name AS participant_name,
       'Single-session enrollment' AS enrollment_type
FROM session s
JOIN person lec
    ON lec.person_id = s.lecturer_id
JOIN enrollment e
    ON e.session_id = s.session_id
JOIN purchase pur
    ON pur.purchase_id = e.purchase_id
JOIN person pe
    ON pe.person_id = pur.participant_id
WHERE s.cycle_id = 10

UNION

SELECT s.session_id,
       s.topic,
       lec.name AS session_lecturer,
       pe.name AS participant_name,
       'Package enrollment' AS enrollment_type
FROM session s
JOIN person lec
    ON lec.person_id = s.lecturer_id
JOIN enrollment e
    ON e.cycle_id = s.cycle_id
JOIN purchase pur
    ON pur.purchase_id = e.purchase_id
JOIN person pe
    ON pe.person_id = pur.participant_id
WHERE s.cycle_id = 10

ORDER BY session_id, participant_name;


-- Q10. Paid recordings currently available to participant 1.
-- Shows the lecturer responsible for the session.

SELECT DISTINCT r.recording_url,
       s.topic,
       lec.name AS session_lecturer,
       s.session_date,
       r.available_until
FROM purchase pur
JOIN payment pay
    ON pay.purchase_id = pur.purchase_id
JOIN enrollment e
    ON e.purchase_id = pur.purchase_id
JOIN session s
    ON s.session_id = e.session_id
    OR s.cycle_id = e.cycle_id
JOIN person lec
    ON lec.person_id = s.lecturer_id
JOIN recording r
    ON r.session_id = s.session_id
WHERE pur.participant_id = 1
  AND CURRENT_DATE BETWEEN r.available_from AND r.available_until
ORDER BY s.session_date;


-- Q11. Payments above the average payment amount.

SELECT pe.name AS participant_name,
       pay.amount_paid,
       pay.payment_date
FROM payment pay
JOIN purchase pur
    ON pur.purchase_id = pay.purchase_id
JOIN person pe
    ON pe.person_id = pur.participant_id
WHERE pay.amount_paid > (
    SELECT AVG(amount_paid)
    FROM payment
)
ORDER BY pay.amount_paid DESC;


-- Q12. Consultation history for patient 551.

SELECT c.consultation_date,
       c.type,
       c.notes,
       pr.decision,
       m.name AS medication_name
FROM consultation c
LEFT JOIN prescription pr
    ON pr.consultation_id = c.consultation_id
LEFT JOIN medication m
    ON m.medication_id = pr.medication_id
WHERE c.patient_id = 551
ORDER BY c.consultation_date;


-- Q13. Invoices already marked as sent.

