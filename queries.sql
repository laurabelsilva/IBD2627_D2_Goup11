-- Q1. Paid training hours for each participant
-- and training program during 2024.
-- Each distinct paid session contributes 2 hours.

SELECT p.participant_id,
       pe.name AS participant_name,
       tp.name AS training_program,
       SUM(v.credited_hours) AS paid_training_hours
FROM v_paid_training_sessions v
JOIN participant p
    ON p.participant_id = v.participant_id
JOIN person pe
    ON pe.person_id = p.participant_id
JOIN training_program tp
    ON tp.training_program_id = v.training_program_id
WHERE v.session_date BETWEEN DATE '2024-01-01'
                         AND DATE '2024-12-31'
GROUP BY p.participant_id, pe.name,
         tp.training_program_id, tp.name
ORDER BY p.participant_id, tp.name;


-- Q2. Participants with paid hours but no certificate for a selected
-- training program and period.

SELECT p.participant_id,
       pe.name AS participant_name,
       tp.name AS training_program,
       fn_paid_training_hours(
           p.participant_id,
           tp.training_program_id,
           DATE '2024-01-01',
           DATE '2024-12-31'
       ) AS paid_hours
FROM participant p
JOIN person pe
    ON pe.person_id = p.participant_id
CROSS JOIN training_program tp
WHERE fn_paid_training_hours(
          p.participant_id,
          tp.training_program_id,
          DATE '2024-01-01',
          DATE '2024-12-31'
      ) > 0
  AND NOT EXISTS (
      SELECT 1
      FROM certificate c
      WHERE c.participant_id = p.participant_id
        AND c.training_program_id = tp.training_program_id
        AND c.period_start = DATE '2024-01-01'
        AND c.period_end = DATE '2024-12-31'
  )
ORDER BY paid_hours DESC, participant_name;


-- Q3. Total paid by each participant during 2024.

SELECT p.participant_id,
       pe.name,
       SUM(pay.amount_paid) AS total_paid
FROM participant p
JOIN person pe
    ON pe.person_id = p.participant_id
JOIN purchase pur
    ON pur.participant_id = p.participant_id
JOIN payment pay
    ON pay.purchase_id = pur.purchase_id
WHERE pay.payment_date BETWEEN DATE '2024-01-01' AND DATE '2024-12-31'
GROUP BY p.participant_id, pe.name
ORDER BY total_paid DESC;


--- Q4. Total value of purchases associated with each training cycle.
-- Includes package and single-session purchases,
-- whether paid or not.

SELECT *
FROM v_revenue_per_cycle
ORDER BY cycle_id;


-- Q5. Participants who purchased more than one training cycle.

SELECT p.participant_id,
       pe.name,
       COUNT(DISTINCT e.cycle_id) AS cycles_purchased
FROM participant p
JOIN person pe
    ON pe.person_id = p.participant_id
JOIN purchase pur
    ON pur.participant_id = p.participant_id
JOIN enrollment e
    ON e.purchase_id = pur.purchase_id
WHERE e.cycle_id IS NOT NULL
GROUP BY p.participant_id, pe.name
HAVING COUNT(DISTINCT e.cycle_id) > 1
ORDER BY cycles_purchased DESC;


-- Q6. Invoices that have not been sent.

